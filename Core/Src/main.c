/* USER CODE BEGIN 4 */
uint32_t Read_ADC(void)
{
    HAL_ADC_Start(&hadc1);
    HAL_ADC_PollForConversion(&hadc1, HAL_MAX_DELAY);
    return HAL_ADC_GetValue(&hadc1);
}

float ADC_To_Voltage(uint32_t adc)
{
    return (adc * 3.3f) / 4095.0f;
}

float Voltage_To_Current(float voltage)
{
    return 4.0f + ((voltage * 16.0f) / 3.3f);
}

float Current_To_Level(float current)
{
    return ((current - 4.0f) * 100.0f) / 16.0f;
}

void Control_Relay(float level)
{
    if (level >= 80.0f)
    {
        HAL_GPIO_WritePin(GPIOE, GPIO_PIN_0, GPIO_PIN_SET);
    }
    else
    {
        HAL_GPIO_WritePin(GPIOE, GPIO_PIN_0, GPIO_PIN_RESET);
    }
}
